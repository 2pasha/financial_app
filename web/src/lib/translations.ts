/**
 * Fills `{name}` placeholders in a translated string.
 *
 * Counts and interpolated values have to sit *inside* the string rather than being
 * concatenated around it: word order differs between the two languages (English
 * "{n} selected" against Ukrainian "Вибрано {n}"), and concatenation would hard-code
 * the English order for both.
 */
export function tf(template: string, vars: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (whole, key) =>
    key in vars ? String(vars[key]) : whole,
  );
}

/**
 * Picks the right plural form for a count.
 *
 * English needs two forms and Ukrainian three, selected by a rule that is not a
 * simple `n === 1` test: 1, 21, 31… take the singular, 2–4 take the "few" form, and
 * 11–14 take the "many" form despite ending in 1–4. Callers pass all three forms and
 * English simply ignores the third.
 */
export function pluralize(
  lang: Language,
  n: number,
  forms: [one: string, few: string, many: string],
): string {
  if (lang === 'en') return n === 1 ? forms[0] : forms[1];

  const mod100 = Math.abs(n) % 100;
  const mod10 = mod100 % 10;

  if (mod100 >= 11 && mod100 <= 14) return forms[2];
  if (mod10 === 1) return forms[0];
  if (mod10 >= 2 && mod10 <= 4) return forms[1];

  return forms[2];
}
